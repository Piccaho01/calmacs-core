#!/usr/bin/env bash
#
# enable-auto-update.sh — make the crew SELF-UPDATING.
#
# Installs a global Claude Code SessionStart hook that, on every session start,
# pulls the latest crew from this repo clone and re-syncs your global ~/.claude/
# (agents + Core Protocol). Edit the crew in the repo once, push, and every
# machine picks it up on the next session — no manual re-install.
#
# Run once per machine:  bash install/enable-auto-update.sh
# (Run install/install-core.sh first, or this will run it for you on first sync.)
#
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CLAUDE_DIR="${HOME}/.claude"
STATE_DIR="${CLAUDE_DIR}/calmac-core"
UPDATER="${STATE_DIR}/update.sh"
SETTINGS="${CLAUDE_DIR}/settings.json"
MARKER="calmac-core/update.sh"   # unique string identifying our hook

mkdir -p "${STATE_DIR}"

# 1. Write the updater the hook will call. It records THIS clone's path, pulls
#    it (fast, offline-safe), and re-syncs. Always exits 0 so it never blocks a
#    session.
cat > "${UPDATER}" <<EOF
#!/usr/bin/env bash
# Auto-generated by enable-auto-update.sh — self-updates the Calmac's Core crew.
SRC="${REPO_DIR}"
[ -d "\$SRC/.git" ] || exit 0
timeout 20 git -C "\$SRC" pull --quiet --ff-only >/dev/null 2>&1 || true
bash "\$SRC/install/install-core.sh" >/dev/null 2>&1 || true
exit 0
EOF
chmod +x "${UPDATER}"
echo "  • Wrote self-updater: ${UPDATER}"

# 2. Merge a SessionStart hook into ~/.claude/settings.json without disturbing
#    anything else, and without adding a duplicate on re-run.
python3 -I - "${SETTINGS}" "${MARKER}" "bash \"\$HOME/.claude/calmac-core/update.sh\"" <<'PY'
import json, os, sys
path, marker, command = sys.argv[1], sys.argv[2], sys.argv[3]
data = {}
if os.path.exists(path):
    try:
        with open(path) as f:
            data = json.load(f) or {}
    except Exception:
        print("  ! settings.json exists but is not valid JSON — not touching it.", file=sys.stderr)
        sys.exit(2)
if not isinstance(data, dict):
    print("  ! settings.json is not an object — not touching it.", file=sys.stderr)
    sys.exit(2)
hooks = data.setdefault("hooks", {})
starts = hooks.setdefault("SessionStart", [])
# already present?
blob = json.dumps(starts)
if marker in blob:
    print("  • SessionStart hook already present — left as is.")
    sys.exit(0)
starts.append({"hooks": [{"type": "command", "command": command}]})
with open(path, "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
print("  • Added SessionStart hook to " + path)
PY

echo ""
echo "Self-update enabled. From now on, each Claude Code session pulls the latest"
echo "crew from ${REPO_DIR} and re-syncs ~/.claude/ automatically."
echo "Disable later: remove the hook entry from ${SETTINGS} and delete ${STATE_DIR}."
